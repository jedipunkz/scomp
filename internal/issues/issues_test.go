func TestCreateAndEdit(t *testing.T) {
	for _, tc := range []struct {
		name   string
		args   []string
		create bool
	}{
		{name: "create", create: true, args: []string{"issue", "create"}},
		{name: "edit", args: []string{"issue", "edit", "12"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			bin, log := fakeGh(t, "\nhttps://github.com/o/r/issues/9\n")
			c := Client{Bin: bin, Scomp: "1.2.3"}
			ctx := context.Background()
			f := testFinding()
			var url string
			var err error
			if tc.create {
				url, err = c.Create(ctx, f)
			} else {
				url, err = c.Edit(ctx, f, 12)
			}
			if err != nil {
				t.Fatalf("got %v", err)
			}
			if url != "https://github.com/o/r/issues/9" {
				t.Errorf("url = %q", url)
			}
			logged := readLog(t, log)
			for _, want := range tc.args {
				if !strings.Contains(logged, want) {
					t.Errorf("args missing %q: %s", want, logged)
				}
			}
			// The title and body are plain arguments; the fake gh logs them
			// via "$*", which flattens them into one blob.
			for _, want := range []string{
				"--title [security] GO-2024-2687: golang.org/x/net 0.12.0 --body",
				"Generated by [scomp](https://github.com/jedipunkz/scomp) v1.2.3",
				"[osv.dev](https://osv.dev/vulnerability/GO-2024-2687)",
				"CVE-2023-39325",
				"`golang.org/x/net`",
				"| Installed version | `0.12.0` |",
				"| Severity | high (CVSS 7.4) |",
				"| Fixed in | 0.17.0 |",
				"| Published | 2023-09-06 |",
				"HTTP/2 rapid reset",
				"Details with ANSI escapes",
				"- https://access.redhat.com/security/cve/CVE-2023-39325",
			} {
				if !strings.Contains(logged, want) {
					t.Errorf("args missing %q:\n%s", want, logged)
				}
			}
		})
	}
}

