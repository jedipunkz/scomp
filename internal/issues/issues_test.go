func TestGHExitError(t *testing.T) {
	dir := t.TempDir()
	out := filepath.Join(dir, "out.txt")
	if err := os.WriteFile(out, nil, 0o600); err != nil {
		t.Fatal(err)
	}
	log := filepath.Join(dir, "args.log")
	script := "#!/bin/sh\nprintf '%s\\n' \"$*\" >> " + strconv.Quote(log) + "\necho 'none of the git remotes point to a GitHub repository' >&2\nexit 1\n"
	bin := filepath.Join(dir, "gh")
	if err := os.WriteFile(bin, []byte(script), 0o700); err != nil {
		t.Fatal(err)
	}
	_, err := (Client{Bin: bin}).Create(context.Background(), testFinding())
	if err == nil || !strings.Contains(err.Error(), "gh issue create: none of the git remotes") {
		t.Errorf("got %v, want stderr surfaced", err)
	}
}
