// fakeGh writes a gh replacement shell script that appends its arguments and
// working directory to a log file and prints out. It returns the script path
// and the log path.
func fakeGh(t *testing.T, out string) (bin, log string) {
	t.Helper()
	dir := t.TempDir()
	outPath := filepath.Join(dir, "out.txt")
	if err := os.WriteFile(outPath, []byte(out), 0o600); err != nil {
		t.Fatal(err)
	}
	logPath := filepath.Join(dir, "args.log")
	script := "#!/bin/sh\n" +
		"printf '%s\\n' \"$(pwd)\" >> " + strconv.Quote(logPath) + "\n" +
		"printf '%s\\n' \"$*\" >> " + strconv.Quote(logPath) + "\n" +
		"cat " + strconv.Quote(outPath) + "\n"
	binPath := filepath.Join(dir, "gh")
	if err := os.WriteFile(binPath, []byte(script), 0o700); err != nil {
		t.Fatal(err)
	}
	return binPath, logPath
}

func readLog(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func testFinding() model.Finding {
	published, _ := time.Parse(time.RFC3339, "2023-09-06T05:04:36Z")
	return model.Finding{
		ID:            "GO-2024-2687",
		Aliases:       []string{"CVE-2023-39325", "GHSA-qppj"},
		CVEs:          []string{"CVE-2023-39325"},
		Summary:       "HTTP/2 rapid reset can cause excessive work in net/http",
		Details:       "Details with ANSI\x1b[31m escapes\nand several lines.",
		Severity:      model.SeverityHigh,
		CVSSScore:     7.4,
		Package:       model.Package{Name: "golang.org/x/net", Version: "0.12.0", Ecosystem: "Go", Source: "go.mod"},
		FixedVersions: []string{"0.17.0"},
		References:    []string{"https://access.redhat.com/security/cve/CVE-2023-39325"},
		Published:     published,
	}
}

func TestSearch(t *testing.T) {
	root := t.TempDir()
	bin, log := fakeGh(t, `[
  {"number":3,"title":"[security] GO-2024-2687: golang.org/x/net 0.10.0","state":"OPEN","url":"https://github.com/o/r/issues/3"},
  {"number":12,"title":"[security] GO-2024-2687: golang.org/x/net 0.12.0","state":"CLOSED","url":"https://github.com/o/r/issues/12"}
]`)
	c := Client{Bin: bin, Dir: root}
	issues, err := c.Search(context.Background(), testFinding())
	if err != nil {
		t.Fatalf("Search: %v", err)
	}
	if len(issues) != 2 {
		t.Fatalf("got %d issues, want 2: %+v", len(issues), issues)
	}
	// Newest first.
	if issues[0].Number != 12 || issues[1].Number != 3 {
		t.Errorf("order: got %d, %d", issues[0].Number, issues[1].Number)
	}
	if issues[0].State != "CLOSED" || issues[0].URL != "https://github.com/o/r/issues/12" {
		t.Errorf("first issue: %+v", issues[0])
	}
	got := readLog(t, log)
	if !strings.Contains(got, `"GO-2024-2687" "golang.org/x/net" in:title`) {
		t.Errorf("search query missing: %s", got)
	}
	if !strings.Contains(got, "--state all --search") || !strings.Contains(got, "--json number,title,state,url --limit 20") {
		t.Errorf("search flags missing: %s", got)
	}
	// macOS reports temp dirs through the /var → /private/var symlink.
	resolved, err := filepath.EvalSymlinks(root)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(got, resolved+"\n") {
		t.Errorf("gh did not run in Dir %s: %q", root, got)
	}
}

